import assert from "node:assert/strict";
import {canvasTextOutputBudget,partialCanvasText} from "../src/lib/canvas/text-output-policy";
import {textResponseEvidence} from "../src/lib/bi/text-response-evidence";
import {synchronousFailureCheckpoint,settledSynchronousFailure} from "../src/lib/billing/synchronous-failure-receipt";
import {modelConfigSchema} from "../src/lib/model-config/schema";
import {fixtureModelConfig} from "./model-config-unit-fixture";
let checks=0;
const eq=(a:unknown,b:unknown)=>{assert.deepEqual(a,b);checks++;};
eq(canvasTextOutputBudget(),{max_tokens:8192});
eq(canvasTextOutputBudget({maxTokens:16384,maxSupportedTokens:4096}),{max_tokens:4096});
eq(canvasTextOutputBudget({maxTokens:4096,tokenParameter:"max_completion_tokens"}),{max_completion_tokens:4096});
eq(canvasTextOutputBudget({maxTokens:Infinity,maxSupportedTokens:-1}),{max_tokens:8192});
eq(canvasTextOutputBudget({maxTokens:100000}),{max_tokens:65536});
const config=fixtureModelConfig("https://fixture.invalid/v1","00000000-0000-4000-8000-000000000001");
config.upstreamModels[0].parameterMap.textOutput={maxTokens:12000,maxSupportedTokens:8192,tokenParameter:"max_completion_tokens"};
eq(modelConfigSchema.parse(config).upstreamModels[0].parameterMap.textOutput,config.upstreamModels[0].parameterMap.textOutput);
const evidence=textResponseEvidence("requested",{model:"reported",choices:[{finish_reason:"length"}],usage:{prompt_tokens:205,completion_tokens:1800,completion_tokens_details:{reasoning_tokens:1500}},messages:[{content:"PRIVATE"}]},8192);
eq(evidence.identity,"different-label-unverified");eq(evidence.finishReason,"length");eq(evidence.reasoningTokens,1500);eq(JSON.stringify(evidence).includes("PRIVATE"),false);
eq(textResponseEvidence("requested",{}).identity,"unreported");
const raw={code:"TEXT_OUTPUT_LIMIT",error:"尚未写完",finishReason:"length",textProject:"tree:A",partialText:"可用的未完成正文",private:"PRIVATE",reasoning_content:"PRIVATE"};
const checkpoint=synchronousFailureCheckpoint(422,raw);
eq(JSON.stringify(checkpoint).includes("PRIVATE"),false);
const receipt=settledSynchronousFailure({id:"tool-original-op",state:"settled",charged_credits:0,result_response:checkpoint,settlement_result:{state:"failed",items:[]}})!;
eq(receipt.httpStatus,422);eq(partialCanvasText(receipt.body,"original-op"),{text:raw.partialText,operationId:"original-op"});
eq(partialCanvasText(receipt.body,"foreign-op"),undefined);eq(partialCanvasText({...receipt.body,terminal:false},"original-op"),undefined);
eq(partialCanvasText({...receipt.body,chargedCredits:-1},"original-op"),undefined);
eq(settledSynchronousFailure({id:"tool-original-op",state:"hold",charged_credits:0,result_response:checkpoint,settlement_result:{state:"unknown",items:[]}}),null);
eq(synchronousFailureCheckpoint(422,{...raw,partialText:"x".repeat(20001)}).partialText,undefined);
console.log(`CANVAS_TEXT_COMPLETION_POLICY=PASS CHECKS=${checks} MODEL_NAME_INFERENCE=0 SUPPLIER_CALLS=0`);
