import assert from "node:assert/strict";
import { CAP_RICH } from "./video-fusion/harness";
import { resolveVideoCapability, normalizeVideoInput, numberVideoInputs, VideoContractError } from "../src/lib/video/contract";
import { compileVideoPrompt } from "../src/lib/video/prompt";
const cap=resolveVideoCapability({manual:{limits:{images:0},audio:"disabled",supportsWatermark:false},vendor:CAP_RICH});
assert.equal(cap.limits?.images,0);assert.equal(cap.audio,"disabled");assert.equal(cap.supportsWatermark,false);
assert.equal(cap.sources["limits.images"],"admin");
const image=(id:string,role="reference")=>({id,kind:"image",role,url:`/media/${id}.png`});
const base={prompt:"完整动作及对白",durationSeconds:4,resolution:"720p",aspectRatio:"16:9"};
const rich=resolveVideoCapability({manual:CAP_RICH});
const one=normalizeVideoInput({...base,mode:"first_optional",references:[image("tail")]},rich);
assert.equal(one.references[0].role,"last_frame");
const start=normalizeVideoInput({...base,mode:"last_optional",references:[image("first")]},rich);
assert.equal(start.references[0].role,"first_frame");
assert.throws(()=>normalizeVideoInput({...base,mode:"frames_required",references:[image("one")]},rich),VideoContractError);
assert.throws(()=>normalizeVideoInput({...base,mode:"reference",references:Array.from({length:31},(_,i)=>image(`i${i}`))},rich),/参考/);
assert.throws(()=>normalizeVideoInput({...base,mode:"reference",references:[image("one")]},cap),/参考/);
assert.throws(()=>normalizeVideoInput({...base,mode:"text",durationSeconds:5,references:[]},rich),/时长/);
assert.throws(()=>normalizeVideoInput({...base,mode:"text",resolution:"4K",references:[]},rich),/分辨率/);
assert.throws(()=>normalizeVideoInput({...base,mode:"text",prompt:"x".repeat(16385),references:[]},rich),/描述/);
assert.throws(()=>normalizeVideoInput({...base,mode:"reference",references:[image("same"),image("same")]},rich),/重复/);
const unknown=resolveVideoCapability({});assert.equal(unknown.audio,null);assert.equal(unknown.modes,null);
assert.throws(()=>normalizeVideoInput({...base,mode:"text",references:[]},unknown),/能力/);
const silent=normalizeVideoInput({...base,mode:"text",references:[],generateAudio:false,watermark:false},rich);
assert.equal(silent.generateAudio,false);assert.equal(silent.watermark,false);
assert.equal(normalizeVideoInput({...base,mode:"text",references:[]},rich).generateAudio,undefined);
const inputs=[{id:"t",nodeId:"t",kind:"text" as const,role:"context" as const,value:"原文对白"},
  {id:"i",nodeId:"i",kind:"image" as const,role:"reference" as const,value:"/media/i.png"}];
const order=numberVideoInputs(inputs);assert.equal(order.all[1].index,2);assert.equal(order.byKind.image[0].index,1);
const compiled=compileVideoPrompt("引用{{ref 2}}，图片1。",inputs);
assert.ok(compiled.prompt.includes("原文对白"));assert.equal(compiled.bindings["ref 2"].id,"i");
assert.ok(!compiled.prompt.includes("{{ref 2}}"));assert.ok(compiled.prompt.includes("图片1"));
assert.throws(()=>compileVideoPrompt("{{ref 3}}",inputs),/引用/);
const combos=resolveVideoCapability({manual:{...CAP_RICH,durationResolutionMap:[{durations:[4],resolutions:["1080p"]},{durations:[8],resolutions:["720p"]}]}});
assert.throws(()=>normalizeVideoInput({...base,durationSeconds:8,resolution:"1080p",mode:"text",references:[]},combos),/分辨率/);
process.stdout.write("VIDEO_CONTRACT=PASS roles=true no_truncation=true priority=true exact_combinations=true\n");
