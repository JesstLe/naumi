import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';

// Canonical authoring files remain portable; the browser/standalone build gets a
// statically bundled definition, not a runtime dependency on a local skill path.
const files = ['SKILL.md', 'references/brief-schema.md', 'references/output-format.md'];
const sources = await Promise.all(files.map(async path => ({path, text: await readFile(new URL(`../skills/brand-packaging-strategy/${path}`, import.meta.url), 'utf8')})));
const definition = {
  id: 'official:brand-packaging-strategy', revision: 1,
  name: '品牌包装创意策略生成器', category: '品牌',
  description: '用客户简报生成包装策略、三个创意方向与明确推荐',
  instructions: sources.map(source => `【${source.path}】\n${source.text.trim()}`).join('\n\n'),
  source: 'official',
};
if (definition.instructions.length > 6000) throw new Error('Packaging skill exceeds workflow limit');
const hashes = Object.fromEntries(sources.map(source => [source.path, createHash('sha256').update(source.text).digest('hex')]));
const content = `// Generated by node scripts/sync-packaging-skill.mjs from skills/brand-packaging-strategy.\nimport type { ImageSkill } from './catalog';\nexport const PACKAGING_SKILL: ImageSkill = ${JSON.stringify(definition, null, 2)};\nexport const PACKAGING_SOURCE_HASHES = ${JSON.stringify(hashes, null, 2)} as const;\n`;
const destination = new URL('../src/lib/image-skills/brand-packaging-strategy.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (await readFile(destination, 'utf8') !== content) throw new Error('Packaging skill bundle is stale');
  console.log('PACKAGING_CANONICAL_BUNDLE=PASS REFERENCES=2');
} else {
  await writeFile(destination, content);
  console.log(`PACKAGING_SKILL_BUNDLED=PASS CHARACTERS=${definition.instructions.length}`);
}
