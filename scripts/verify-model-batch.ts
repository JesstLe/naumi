import assert from "node:assert/strict";
import { fixtureModelConfig } from "./model-config-unit-fixture";
import { batchFeatureAvailability, planModelBatch, type BatchInput } from "../src/lib/model-config/batch";
import { validateModelConfig } from "../src/lib/model-config/schema";
import { publicModelCatalog } from "../src/lib/model-config/runtime";

const config = fixtureModelConfig("https://fixture.example/v1", "00000000-0000-4000-8000-000000000001");
const pricing: BatchInput["pricing"] = { mode: "cny-fixed", amountMicros: "650000", creditsPerCnyMicros: "100000000", rounding: "ceil" };
const input: BatchInput = { mode: "new", modelId: "public-ext25", label: "灵动 2.5", upstreamId: "u1", features: ["image.generate", "tool.garment", "canvas.image"], pricing, unit: "image", overwritePrice: false, direct: false, setDefault: true };
const original = JSON.stringify(config);
const result = planModelBatch(config, input);
assert.equal(JSON.stringify(config), original);
validateModelConfig(result.config);
for (const feature of input.features) {
  const c = publicModelCatalog({ version: 2, digest: "fixture", config: result.config }, "image", feature);
  assert.equal(c.defaultModelId, input.modelId); assert.equal(c.models[0].label, input.label);
  assert.deepEqual(result.config.business?.[feature]?.options[0].pricing, pricing);
}
assert.deepEqual(result.config.bindings, config.bindings, "unselected purposes must not change");
assert.equal(result.config.publicModels.find(m => m.id === input.modelId)?.target.id, "u1");
const availability = batchFeatureAvailability(config, "u1");
for (const feature of ["canvas.text-generate", "video.generate", "tool.cutout"]) assert.equal(availability.find(a => a.feature === feature)?.compatible, false);
assert.equal(availability.find(a=>a.feature==="tool.upscale")?.compatible,true,"upscale uses the current image.edit contract");
assert.equal(availability.find(a=>a.feature==="tool.printfile")?.compatible,true,"printfile uses the current image.edit contract");
assert.throws(() => planModelBatch(config, { ...input, features: ["image.generate", "tool.cutout"] }), /不兼容/);
assert.equal(JSON.stringify(config), original, "invalid batch must be atomic");
assert.throws(() => planModelBatch(config, { ...input, label: " " }));
assert.throws(() => planModelBatch(config, { ...input, modelId: "image-a" }));
assert.throws(() => planModelBatch(config, { ...input, features: [] }));
assert.throws(() => planModelBatch(config, { ...input, pricing: { ...pricing, creditsPerCnyMicros: "0" } }));
const edited = structuredClone(result.config);
const exception = edited.business!["tool.garment"]!.options[0];
exception.pricing = { ...pricing, amountMicros: "900000", variants: [{ resolution: "2K", amountMicros: "1200000" }] };
exception.parameters = { qualities: ["medium"] };
exception.postprocess = { enabled: false, kind: "resize", processor: "sharp-lanczos3", width: 2048, height: 2048, failure: "hold" };
exception.routing = { enabled: true, defaultUpstreamId: "u1", maxAttempts: 1, costCapCnyMicros: "10000000", rules: [] };
const reuse = { ...input, mode: "existing" as const };
const preserved = planModelBatch(edited, reuse);
assert.deepEqual(preserved.config.business!["tool.garment"]!.options[0], exception);
const overwritten = planModelBatch(edited, { ...reuse, overwritePrice: true, direct: true });
const changed = overwritten.config.business!["tool.garment"]!.options[0];
assert.deepEqual(changed.pricing, pricing); assert.equal(changed.routing?.enabled, false);
assert.deepEqual(changed.parameters, exception.parameters); assert.deepEqual(changed.postprocess, exception.postprocess);
assert.deepEqual(planModelBatch(result.config, reuse).config, result.config, "repeated draft application is idempotent");
const disabled = structuredClone(result.config); disabled.business!["tool.garment"]!.enabled = false;
assert.throws(() => planModelBatch(disabled, reuse), /停用/);
const unverified = structuredClone(config); unverified.upstreamModels[0].capabilities.verified = false;
assert.throws(() => planModelBatch(unverified, input), /未核验/);
const masked = structuredClone(config); masked.upstreamModels[0].capabilities.edit = false;
assert.equal(batchFeatureAvailability(masked, "u1").find(a => a.feature === "canvas.image")?.compatible, true, "plain canvas generation needs no editing capability");
assert.equal(batchFeatureAvailability(masked, "u1").find(a => a.feature === "tool.retouch")?.compatible, false);
masked.upstreamModels[0].capabilities.generate = false;
assert.equal(batchFeatureAvailability(masked, "u1").find(a => a.feature === "canvas.image")?.compatible, false);
const wrong = structuredClone(result.config); wrong.publicModels.find(m => m.id === input.modelId)!.target = { type: "pool", id: "other" };
assert.throws(() => planModelBatch(wrong, reuse), /复用模型/);
console.log("MODEL_BATCH=PASS COMPATIBILITY=PASS ATOMIC=PASS PUBLIC_ALIAS=PASS PRESERVE_EXCEPTIONS=PASS EXPLICIT_OVERRIDE=PASS IDEMPOTENT=PASS DISABLED_PROTECTED=PASS UNSELECTED_UNCHANGED=PASS PAID_POSTS=0");
