import assert from 'node:assert/strict';
import { build } from 'esbuild';
import { createServer } from 'node:http';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { chromium, expect } from '@playwright/test';
const out = path.resolve('output/orb-full-state-companion-20261012/browser');
await mkdir(out, { recursive: true });
await build({entryPoints:['scripts/orb-companion-browser-fixture.tsx'],outfile:out+'/fixture.js',bundle:true,format:'iife',platform:'browser',jsx:'automatic',define:{'process.env.NODE_ENV':'"production"'},logLevel:'error'});
const server=createServer(async(req,res)=>{
  const file=req.url==='/fixture.js'?'fixture.js':req.url==='/fixture.css'?'fixture.css':null;
  res.setHeader('content-type',file?.endsWith('.js')?'application/javascript':file?'text/css':'text/html');
  res.end(file?await readFile(out+'/'+file):'<!doctype html><html><head><link rel="stylesheet" href="/fixture.css"></head><body style="margin:0"><div id="root"></div><script src="/fixture.js"></script></body></html>');
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
let browser;const seen=new Set(),errors=[];let checks=0;
try{
  browser=await chromium.launch({channel:process.platform==='win32'?'msedge':undefined,headless:true});
  const page=await browser.newPage({viewport:{width:960,height:720},reducedMotion:'reduce'});
  page.on('pageerror',e=>errors.push(e.message));
  await page.clock.install({time:new Date('2026-10-12T08:00:00Z')});
  await page.goto(`http://127.0.0.1:${server.address().port}`);
  const orb=page.locator('[data-testid="canvas-agent-orb"] [data-orb-state]');
  await expect(orb.locator('svg')).toHaveCount(1);
  const face=async state=>{await expect(orb).toHaveAttribute('data-orb-state',state);seen.add(state);checks++;};
  const cue=async event=>{await page.evaluate(event=>window.orbTest.emit(event),event);};
  const advance=async ms=>{await page.clock.fastForward(ms);};
  const spaced=async event=>{await advance(3000);await cue(event);};
  await face('booting');await advance(650);await face('waking');await advance(900);await face('idle');
  await advance(45000);await face('daydreaming');await advance(180000);await face('drowsy');await advance(300000);await face('sleeping');
  const sleepingBox=await page.getByTestId('canvas-agent-orb').boundingBox();
  await page.mouse.move(sleepingBox.x+40,sleepingBox.y+40);await face('sleeping');
  await page.mouse.down();await page.mouse.move(sleepingBox.x+20,sleepingBox.y+65,{steps:2});await page.mouse.up();
  await face('jolted');await advance(900);await face('idle');
  await spaced({type:'hover'});await face('curious');
  await spaced({type:'draft',text:'???'});await face('puzzled');
  await spaced({type:'draft',text:'分析商品图'});await face('focused');
  await spaced({type:'feedback',positive:true});await face('happy');
  await spaced({type:'feedback',positive:true});await face('shy');
  await spaced({type:'copied'});await face('content');
  await cue({type:'submit'});await face('receiving');await advance(650);await face('connecting');
  await cue({type:'connected'});await face('thinking');
  await cue({type:'tool-start',tool:'search_templates'});await face('searching');
  await cue({type:'tool-start',tool:'generate_image'});await face('working');
  await cue({type:'delta'});await face('replying');
  await spaced({type:'tool-end',error:true});await face('flustered');
  await spaced({type:'tool-end',error:true});await face('resigned');
  await spaced({type:'tool-end',error:true});await face('frustrated');
  await advance(60000-9650);await face('tired');await advance(2400);await face('thinking');
  await cue({type:'attention',kind:'waiting'});await face('waiting');await cue({type:'done'});await face('waiting');
  await expect(page.locator('[role="status"]')).toHaveText('等待输入');checks++;
  await cue({type:'submit'});await cue({type:'attention',kind:'restricted'});await cue({type:'done'});await face('restricted');
  await cue({type:'stop'});await face('stopped');await cue({type:'hover'});await face('stopped');
  await cue({type:'reset'});await cue({type:'submit'});await cue({type:'artifacts',count:2});await cue({type:'done'});await face('done');
  await advance(2500);await face('surprised');await expect(page.locator('[role="status"]')).toHaveText('已完成');checks++;
  await advance(1600);await cue({type:'restore',running:false,outcome:'done'});await face('remembering');
  await cue({type:'failure',code:'NETWORK'});await face('error');await advance(2500);await face('sad');
  await cue({type:'failure',code:'VALIDATION'});await advance(2500);await face('confused');
  await cue({type:'reset'});await cue({type:'submit'});
  await expect(page.getByTestId('independent')).toHaveAttribute('data-busy','false');checks++;
  await page.evaluate(()=>window.orbTest.setScope('fixture:p2'));await face('booting');
  await page.evaluate(()=>window.orbTest.oldEmit({type:'reset'}));await page.evaluate(()=>window.orbTest.oldEmit({type:'failure',code:'NETWORK'}));await face('booting');
  assert.equal(seen.size,32);assert.deepEqual(errors,[]);checks+=2;
  // Real pointer capture: dragging moves the orb without toggling the panel.
  const floating=page.getByTestId('canvas-agent-orb'),before=await floating.boundingBox();
  await page.mouse.move(before.x+40,before.y+40);await page.mouse.down();await page.mouse.move(before.x-200,before.y+160,{steps:4});await page.mouse.up();
  const after=await floating.boundingBox();assert.ok(Math.abs(after.x-before.x)>150);await expect(page.getByTestId('opened')).toHaveText('false');checks+=2;
  await page.screenshot({path:out+'/companion.png'});
  await writeFile(out+'/result.json',JSON.stringify({checks,reachable:[...seen],errors,paidCalls:0},null,2));
  console.log(`ORB_COMPANION_BROWSER=PASS checks=${checks} REACHABLE=${seen.size}/32 REAL_REACT_HOOK=PASS REAL_SVG=PASS REDUCED_MOTION=PASS DRAG=PASS STALE_SCOPE_CUES=BLOCKED PROVIDER_CALLS=0`);
}finally{await browser?.close();await new Promise(resolve=>server.close(resolve));}
