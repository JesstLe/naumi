import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { createEdgeHoverController, type EdgeHoverPoint } from "../src/lib/canvas/edge-hover";

const frames = new Map<number, () => void>();
const cancelled: number[] = [], paints: Array<EdgeHoverPoint | null> = [];
let sequence = 0;
const controller = createEdgeHoverController(point => paints.push(point), callback => {
  const id = sequence++; frames.set(id, callback); return id;
}, id => { cancelled.push(id); });
for (let i = 0; i < 1000; i++) controller.show({ x: i, y: i / 2 });
assert.equal(frames.size, 1, "1000 pointer events coalesce into one frame, including frame id 0");
assert.equal(paints.length, 0, "no synchronous per-event DOM/layout work");
frames.get(0)!(); frames.delete(0);
assert.deepEqual(paints, [{ x: 999, y: 499.5 }]);
controller.show({ x: -4, y: 25 });
const stale = frames.get(1)!;
controller.clear();
assert.deepEqual(cancelled, [1]); assert.equal(paints.at(-1), null);
controller.show({ x: 30, y: 40 });
stale();
assert.equal(paints.at(-1), null, "cancelled callback cannot resurrect the old edge hint");
frames.get(2)!();
assert.deepEqual(paints.at(-1), { x: 30, y: 40 }, "new gesture remains valid after clearing");
controller.clear();
const before = paints.length;
for (const invalid of [{ x: NaN, y: 0 }, { x: Infinity, y: 0 }, { x: 0, y: -Infinity }]) controller.show(invalid);
assert.equal(paints.length, before);
controller.show({ x: -10, y: -2 }); frames.get(3)!();
assert.deepEqual(paints.at(-1), { x: -10, y: -2 }, "existing out-of-bounds geometry is not clamped");
controller.clear();
const client = readFileSync("src/components/canvas/canvas-client.tsx", "utf8");
assert.doesNotMatch(client, /setEdgeCut|\[edgeCut/);
assert.match(client, /CanvasEdgeHoverHint key=\{activeKey/);
assert.match(client, /canvasTool === "hand" \|\| ev\.buttons \|\| edge\.selectable === false/);
assert.match(client, /onEdgeClick[\s\S]*setSelectedEdge\(\{ id: edge\.id/);
const hint = readFileSync("src/components/canvas/canvas-edge-hover-hint.tsx", "utf8");
assert.match(hint, /pointer-events-none/); assert.match(hint, /useEffect\(\(\) => \(\) => controller\.clear\(\)/);
assert.doesNotMatch(hint, /fetch\(|useState\(/);
console.log("EDGE_HOVER=PASS POINTER1000_FRAME1_LATEST_POINT NO_ROOT_GRAPH_STATE CLEAR_CANCEL_RACE PROJECT_UNMOUNT_CLEAN HAND_BUTTONS_READONLY_GUARDS SELECTION_DELETE_NATIVE NO_MEDIA_WRITE");
