import assert from "node:assert/strict";
import { existsSync } from "node:fs";
import path from "node:path";
async function main() {
    assert.ok(existsSync(path.resolve("src/lib/billing/quote.ts")), "Configuration-driven quotes must exist");
    const { fixtureConfig, facts } = await import("./billing-unit-fixture");
    const { quote, settlementFor } = await import("../src/lib/billing/quote");
    const { validateBillingConfig } = await import("../src/lib/billing/rules/schema");
    const { estimateCost } = await import("../src/lib/billing/costs");
    const config = fixtureConfig();
    assert.equal(quote({ version: 1, config }, facts({ quality: "high", resolution: "2K" })).requestedCredits, 12);
    const q = quote({ version: 1, config }, facts({ quantity: 2 }));
        assert.equal(q.debitOrder,"expires-first");
        config.credits.debitOrder="created-first";
        assert.equal(q.debitOrder,"expires-first");
    assert.deepEqual(settlementFor(q, { state: "succeeded", items: [{ id: "a", state: "succeeded", executedQuality: "medium" }, { id: "b", state: "failed" }] }), { state: "settle", charge: 6, release: 6 });
    assert.equal(settlementFor(q, { state: "unknown", items: [] }).state, "hold");
    config.features["image.generate"].pricing = { mode: "fixed", credits: 8 };
    assert.equal(quote({ version: 2, config }, facts()).requestedCredits, 8);
    assert.equal(q.requestedCredits, 12);
    assert.throws(() => validateBillingConfig({ ...config, schemaVersion: 99 }));
    assert.throws(() => quote({ version: 1, config }, facts({ quantity: -1 })));
    assert.throws(() => settlementFor(q, { state: "succeeded", items: [{ id: "a", state: "succeeded" }, { id: "a", state: "succeeded" }] }));
    const executed = fixtureConfig();
    executed.features["image.generate"].settlement.qualityBasis = "executed";
    const x = quote({ version: 3, config: executed }, facts({ quality: "high" }));
    assert.equal(settlementFor(x, { state: "succeeded", items: [{ id: "a", state: "succeeded", executedQuality: "medium" }] }).charge, 6);
    const under = fixtureConfig();
    under.features["image.generate"].settlement.reserveBps = 0;
    assert.throws(() => validateBillingConfig(under));
    const failure = fixtureConfig();
    failure.features["image.generate"].settlement.failureBps = 2500;
    const fq = quote({ version: 4, config: failure }, facts({ quantity: 2 }));
    assert.deepEqual(settlementFor(fq, { state: "failed", items: [] }), { state: "settle", charge: 3, release: 9 });
    const byok = fixtureConfig();
    assert.equal(quote({ version: 1, config: byok }, facts({ byok: true })).requestedCredits, 0);
    byok.features["image.generate"].settlement.byokBps = 1;
    const fractional = quote({ version: 5, config: byok }, facts({ quantity: 2, byok: true }));
    assert.equal(fractional.authorizedCredits, 1);
    assert.equal(settlementFor(fractional, { state: "succeeded", items: [{ id: "one", state: "succeeded" }, { id: "two", state: "succeeded" }] }).charge, 1);
    const whole = fixtureConfig();
    whole.features["image.generate"].settlement.successBasis = "whole-request";
    whole.features["image.generate"].settlement.failureBps = 5000;
    const wq = quote({ version: 6, config: whole }, facts({ quantity: 2 }));
    assert.equal(settlementFor(wq, { state: "succeeded", items: [{ id: "one", state: "succeeded" }, { id: "two", state: "failed" }] }).charge, 12);
    const costConfig = fixtureConfig();
    costConfig.costs["tool.cutout"] = { currency: "CNY", amountMicros: "12345", unit: "task", source: "manual-estimate" };
    const cq = quote({ version: 7, config: costConfig }, facts({ feature: "tool.cutout", quantity: 2 }));
    assert.deepEqual(estimateCost(cq, { state: "succeeded", items: [{ id: "1", state: "succeeded" }, { id: "2", state: "succeeded" }] }), { currency: "CNY", amountMicros: "12345", source: "manual-estimate", actual: false });
    costConfig.costs.usd = { currency: "USD", amountMicros: "2000000", unit: "image", cnyPerUnitMicros: "7000000", source: "manual-estimate" };
    costConfig.features["image.generate"].pricing = { mode: "cost-plus", costKey: "usd", creditsPerCnyMicros: "10000000", factorBps: 10000, rounding: "ceil", minimum: 0, maximum: 1000 };
    assert.equal(quote({ version: 8, config: validateBillingConfig(costConfig) }, facts()).requestedCredits, 140);
    const rules = fixtureConfig();
    rules.features["image.generate"].rules = [{ id: "high-only", priority: 1, when: { quality: ["high"] }, pricing: { mode: "fixed", credits: 7 } }];
    assert.equal(quote({ version: 9, config: validateBillingConfig(rules) }, facts({ quality: "high" })).requestedCredits, 7);
    assert.equal(quote({ version: 9, config: rules }, facts()).requestedCredits, 6);
    rules.features["image.generate"].rules.push({ id: "conflict", priority: 1, when: {}, pricing: { mode: "fixed", credits: 9 } });
    assert.throws(() => validateBillingConfig(rules));
    console.log("PASS dynamic quotes, frozen prices, partial/failure/BYOK policies, result validation");
}
main().catch(error => { console.error(error); process.exitCode = 1; });
