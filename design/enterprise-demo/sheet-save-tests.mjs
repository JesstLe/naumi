import assert from 'node:assert/strict';
import {existsSync} from 'node:fs';
if(!existsSync(new URL('sheet-save-model.js',import.meta.url))){console.log('SHEET_SAVE_BASELINE: recovery_model=missing conflict_resolution=missing');process.exit(2);}
await import('./sheet-save-model.js');
const M=globalThis.SheetSaveModel;let checks=0;const ok=(v,name)=>{assert(v,name);checks++;};
const base={columns:[{id:'title',type:'text',label:'名称'},{id:'note',type:'text',label:'说明'},{id:'files',type:'files',label:'附件'}],rows:[{id:'r',parentId:null,archived:false,cells:{title:'原名称',note:'原说明',files:[]}}]};
const a={type:'set-cells',row:'r',cells:{title:'我的名称'}};
const copy=()=>structuredClone(base);
ok(M.plan(base,copy(),a).safe,'unchanged target can be retried');
let next=copy();next.rows[0].cells.note='同事说明';ok(M.plan(base,next,a).safe,'unrelated field preserves colleague data');
next.rows[0].cells.title='同事名称';let p=M.plan(base,next,a);ok(!p.safe&&p.conflicts.length===1,'same field conflict');
ok(p.conflicts[0].before==='原名称'&&p.conflicts[0].latest==='同事名称'&&p.conflicts[0].mine==='我的名称','three values preserved');
ok(M.resolve(a,p,{title:'latest'}).cells.title==='同事名称','choose latest');
ok(M.resolve(a,p,{title:'mine'}).cells.title==='我的名称','choose mine explicitly');
assert.throws(()=>M.resolve(a,p,{}));checks++;
ok(a.cells.title==='我的名称','resolution does not mutate original action');
next.rows[0].cells.title='我的名称';ok(M.plan(base,next,a).safe,'converged values');
next=copy();next.rows[0].archived=true;ok(M.plan(base,next,a).blocked,'deleted row blocks rebase');
next=copy();next.columns[0].type='number';ok(M.plan(base,next,a).blocked,'changed field structure blocks rebase');
next=copy();next.columns.splice(0,1);ok(M.plan(base,next,a).blocked,'deleted column blocks rebase');
ok(M.plan(base,copy(),{type:'delete-row',row:'r'}).blocked,'structural actions require reopening');
next=copy();next.rows[0].parentId='p';p=M.plan(base,next,{...a,parentId:'q'});ok(p.conflicts.some(x=>x.id==='@parent'),'parent conflicts explicit');
ok(M.resolve({...a,parentId:'q'},p,{'@parent':'latest'}).parentId==='p','parent latest selection');
ok(M.plan(base,copy(),{...a,cells:{files:[{id:'1',name:'a.xlsx',kind:'source'}]}}).blocked,'file mutations use dedicated workflow');
ok(M.key({b:1,a:2})===M.key({a:2,b:1}),'fingerprint stable key order');
for(const status of [0,408,500,502,503,504])ok(M.outcome({status})==='unknown','ambiguous response');
for(const status of [400,401,403,404,413,422,429])ok(M.outcome({status})==='rejected','definitive rejection');
ok(M.outcome({status:409,code:'VERSION_CONFLICT'})==='conflict','machine code conflict');
ok(M.outcome({status:409,message:'IDEMPOTENCY_CONFLICT'})==='unknown','different command fingerprint must not resubmit');
ok(M.outcome({status:409,message:'ROW_ARCHIVED'})==='rejected','other conflict definitively rejected');
console.log(`SHEET_SAVE_MODEL_PASS: checks=${checks} three_way=1 unknown_replay=1 no_automatic_overwrite=1`);
