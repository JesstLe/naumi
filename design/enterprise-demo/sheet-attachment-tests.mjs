latest.rows[0].cells.files=[a1];action={...action,cells:{files:[]}};plan=S.plan(document,latest,action);ok(plan.conflicts[0].kind==='attachment','attachment conflicts have separate selectors');
ok(plan.conflicts[0].latest.includes(a1.excelRevision.slice(0,10)),'comparison exposes revision marker');
ok(S.resolve(action,plan,{[plan.conflicts[0].id]:'latest'}).cells.files[0].excelRevision===a1.excelRevision,'worksheet explicit latest');
assert.throws(()=>S.resolve(action,plan,{}));checks++;
ok(action.cells.files.length===0,'resolution keeps original command immutable');
const image=structuredClone(document);image.columns[0].type='image';ok(S.plan(image,image,{type:'set-cells',row:'r',cells:{files:[]}}).safe,'image attachment collection also supported');
ok(M.label(null)==='（未关联）','removed association explicit');
console.log(`ATTACHMENT_SAVE_MODEL_PASS: checks=${checks} collection_three_way=1 revision_conflict=1 no_automatic_overwrite=1`);
