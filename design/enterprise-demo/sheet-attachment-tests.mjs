import assert from 'node:assert/strict';
import './sheet-attachment-model.js';
import './sheet-save-model.js';
const M=globalThis.SheetAttachmentModel,S=globalThis.SheetSaveModel;let checks=0;const ok=(v,name)=>{assert(v,name);checks++;};
const a={kind:'source',id:'a',name:'a.xlsx'},b={kind:'worksheet',id:'b',name:'b.txt'},c={kind:'worksheet',id:'c',name:'c.txt'},d={kind:'worksheet',id:'d',name:'d.txt'};
const merge=(base,latest,mine,choices)=>M.resolve(M.plan(base,latest,mine),choices);
ok(merge([a],[a],[a]).length===1,'unchanged list');
ok(merge([a],[a,b],[a,c]).map(M.id).join(',')==='source:a,worksheet:b,worksheet:c','independent additions');
ok(merge([a,b],[a,b,c],[b]).map(M.id).join(',')==='worksheet:b,worksheet:c','removal preserves unrelated addition');
ok(merge([a,b],[a],[a,c]).map(M.id).join(',')==='source:a,worksheet:c','colleague removal preserved');
ok(merge([a],[a,b],[a,b]).length===2,'same addition deduplicated');
ok(merge([a,b],[a],[a]).length===1,'same removal converges');
const a1={...a,excelRevision:'1'.repeat(64)},a2={...a,excelRevision:'2'.repeat(64)};
ok(merge([a],[a1,b],[a,c])[0].excelRevision===a1.excelRevision,'untouched file preserves colleague revision');
let plan=M.plan([a1],[a2],[]);ok(plan.conflicts.length===1,'remove vs revised file conflict');
ok(M.resolve(plan,{'source:a':'latest'})[0].excelRevision===a2.excelRevision,'explicit latest keeps revised file');
ok(M.resolve(plan,{'source:a':'mine'}).length===0,'explicit mine removes revised link');
assert.throws(()=>M.resolve(plan));checks++;
plan=M.plan([a],[a1],[a2]);ok(plan.conflicts.length===1,'two Excel revisions are never content merged');
ok(M.resolve(plan,{'source:a':'latest'})[0].excelRevision===a1.excelRevision,'latest revision choice');
ok(M.resolve(plan,{'source:a':'mine'})[0].excelRevision===a2.excelRevision,'mine revision choice');
ok(M.plan([a],[],[a1]).conflicts.length===1,'revision cannot resurrect concurrent removal silently');
ok(merge([a],[a1],[a1])[0].excelRevision===a1.excelRevision,'same revision converges');
assert.throws(()=>M.plan([a,a],[a],[a]));checks++;
assert.throws(()=>M.plan([a],[a],['bad']));checks++;
const many=Array.from({length:50},(_,i)=>({...d,id:String(i)}));assert.throws(()=>merge([],many,[{...d,id:'extra'}]));checks++;
const document={columns:[{id:'files',type:'files',label:'附件'}],rows:[{id:'r',archived:false,parentId:null,cells:{files:[a]}}]};
